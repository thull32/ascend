def merge_sorted(a, b):
    sentinel = ListNode(0)
    tail = sentinel
    while a is not None and b is not None:
        if a.val <= b.val:
            tail.next = a
            a = a.next
        else:
            tail.next = b
            b = b.next
        tail = tail.next
    tail.next = a if a is not None else b
    return sentinel.next
